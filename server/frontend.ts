import type { Express } from 'express';
import { resolve, sep } from 'node:path';
import { realpath } from 'node:fs/promises';
import { createServer } from 'vite';

export async function mountDevelopment(
  app: Express,
  options: { root?: string; dataDir?: string; configFile?: false; hmrPort?: number } = {},
) {
  const root = resolve(options.root ?? '.');
  const sourceRoots = await Promise.all(
    ['src', 'shared', 'node_modules'].map(async (directory) => {
      const path = resolve(root, directory);
      return realpath(path).catch(() => path);
    }),
  );
  // Vite is a source-file server. Only browser code may reach its middleware:
  // never serve repository documents, server files, credentials or database data.
  app.use(async (req, res, next) => {
    let path: string;
    try {
      path = decodeURIComponent(req.path);
    } catch {
      res.status(404).end();
      return;
    }
    const valid =
      ['GET', 'HEAD'].includes(req.method) &&
      !path.includes('\\') &&
      !path.includes('\0') &&
      !path.split('/').some((part) => part === '..') &&
      (['/', '/index.html', '/@vite/client', '/@vite/env', '/@react-refresh'].includes(path) ||
        ['/src/', '/shared/', '/node_modules/'].some((prefix) => path.startsWith(prefix)));
    if (!valid) {
      res.status(404).end();
      return;
    }
    if (['/src/', '/shared/', '/node_modules/'].some((prefix) => path.startsWith(prefix))) {
      try {
        // Resolve symbolic links before handing a path to Vite plugins. Its
        // deny list alone cannot cover every alternate plugin load path.
        const actual = await realpath(resolve(root, `.${path}`));
        if (!sourceRoots.some((allowed) => actual.startsWith(`${allowed}${sep}`))) {
          res.status(404).end();
          return;
        }
      } catch (error) {
        // Optimized dependency files may be generated by Vite on first use.
        if ((error as NodeJS.ErrnoException).code !== 'ENOENT') {
          res.status(404).end();
          return;
        }
      }
    }
    next();
  });
  const vite = await createServer({
    root,
    configFile: options.configFile,
    publicDir: false,
    server: {
      middlewareMode: true,
      ...(options.hmrPort ? { hmr: { host: '127.0.0.1', port: options.hmrPort } } : {}),
      fs: {
        strict: true,
        allow: [
          resolve(root, 'src'),
          resolve(root, 'shared'),
          resolve(root, 'node_modules'),
          resolve(root, 'index.html'),
        ],
        deny: [
          '.env',
          '.env.*',
          '*.{crt,pem,key,p12,pfx,cer,der}',
          '.npmrc',
          '.yarnrc.yml',
          '**/.git/**',
          '**/.local/**',
          '**/.cache/**',
          '**/private/**',
          '**/uploads/**',
          '**/mail-data/**',
          `${resolve(options.dataDir ?? '.local/postgres')}/**`,
        ],
      },
    },
    appType: 'spa',
  });
  app.use(vite.middlewares);
  return vite;
}
